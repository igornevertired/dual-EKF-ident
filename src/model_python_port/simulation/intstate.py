"""
Формирование вектора состояния из заданных условий полёта (порт INTSTATE.m).
"""

import numpy as np


def intstate(H0, V0, THETA0, BETA0, GAM0, PSI0, L0, Z0, W0, BAL):
    """
    Собирает 25-компонентный вектор состояния ``x`` для модели динамики FX1.

    По заданной воздушной скорости ``V0``, углам тангажа траектории ``THETA0``,
    скольжения ``BETA0``, крена ``GAM0``, курса ``PSI0`` и вектору балансировки
    ``BAL`` (тяга, угол атаки в скоростной системе, отклонения рулей) вычисляются
    проекции скорости в связанной СК, тангаж ``tet``, координаты и нулевые
    географические углы, нулевой ветер и начальные переменные посадочного контура.

    Параметры
    ---------
    H0, L0, Z0 : float
        Высота и горизонтальные координаты в принятой модели.
    V0, THETA0, BETA0, GAM0, PSI0 : float
        Скорость и углы, рад (кроме скорости — м/с).
    W0 : sequence of float
        Начальная угловая скорость в связанной СК, три компоненты.
    BAL : sequence of float
        Пять параметров балансировки ``[δT, α, δV, δN, δE]``.

    Возвращает
    ----------
    ndarray, shape (25,)
        Вектор состояния в порядке, согласованном с FX1.m.
    """
    v = float(V0)
    alp = float(BAL[1])
    bet = float(BETA0)
    w0 = np.asarray(W0, dtype=float)

    vx1 = v * np.cos(bet) * np.cos(alp)
    vy1 = -v * np.cos(bet) * np.sin(alp)
    vz1 = v * np.sin(bet)
    tet = alp + float(THETA0)

    return np.array(
        [
            vx1,
            vy1,
            vz1,
            w0[0],
            w0[1],
            w0[2],
            GAM0,
            PSI0,
            tet,
            L0,
            H0,
            Z0,
            0.0,  # FI
            0.0,  # LAMD
            0.0,  # d
            BAL[0],  # deltaT
            BAL[2],  # deltaV
            BAL[3],  # deltaN
            BAL[4],  # deltaE
            0.0,  # Vwx1
            0.0,  # Vwy1
            0.0,  # Vwz1
            15.0,  # HFL
            0.0,  # EPS
            0.0,  # X1
        ],
        dtype=float,
    )
