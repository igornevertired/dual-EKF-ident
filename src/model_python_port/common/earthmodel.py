"""
Модель гравитационного поля и радиусов Земли
"""

import numpy as np


def earthmodel(H: float, FI: float, LAMD: float):
    """
    По геодезической широте ``FI``, долготе ``LAMD`` и высоте ``H`` над эллипсоидом
    Красовского вычисляются радиусы кривизны, расстояние до центра Земли, вектор
    истинной гравитации и кажущаяся сила тяжести с учётом вращения планеты.

    Параметры
    ---------
    H : float
        Высота над эллипсоидом, м.
    FI, LAMD : float
        Широта и долгота, рад.

    Возвращает
    ----------
    Gg : ndarray, shape (3,)
        Вектор истинной гравитации ``[Gfi; Gn; 0]``, м/с².
    R1, R2 : float
        Радиусы кривизны (меридиан и первый вертикал) с учётом ``H``, м.
    GTg : ndarray, shape (3,)
        Кажущееся ускорение силы тяжести ``[0; GTn; 0]``, м/с².
    """
    # --- Константы поля и эллипсоида (Красовский) ---
    d00 = 39861679.0e7  # коэффициент монопольной составляющей гравитации
    d20 = 175519.0e20  # коэффициент квадрупольной поправки
    Ue = 7292115.0e-11  # угловая скорость вращения Земли, рад/с
    a = 6378245.0  # большая полуось, м
    b = 6356856.0  # малая полуось, м
    e2 = (a**2 - b**2) / a**2  # квадрат эксцентриситета

    # --- Связь геодезической FI и геоцентрической широты FIe ---
    sin_fi = np.sin(FI)
    sin_mu = e2 * sin_fi * np.cos(FI) / np.sqrt(1.0 - (2 * e2 - e2**2) * sin_fi**2)
    cos_mu = (1.0 - e2 * sin_fi**2) / np.sqrt(1.0 - (2 * e2 - e2**2) * sin_fi**2)
    mu = np.arcsin(sin_mu)
    fi_e = FI - mu  # геоцентрическая широта (для r и квадруполя)

    # --- Радиусы кривизны + H и декартовы координаты точки (для r) ---
    chi = np.sqrt(1.0 - e2 * sin_fi**2)
    R1 = a / chi + H  # меридианный радиус + высота
    R2 = a * (1.0 - e2) / chi**3 + H  # радиус первого вертикала + высота
    xe = (a / chi + H) * np.cos(FI) * np.sin(LAMD)
    ye = (a * (1.0 - e2) / chi + H) * sin_fi
    ze = (a / chi + H) * np.cos(FI) * np.cos(LAMD)
    r = np.sqrt(xe**2 + ye**2 + ze**2)  # расстояние от центра Земли до точки

    # --- Радиальная и «широтная» составляющие гравитации (квадруполь) ---
    gr = -d00 / (r**2) - 1.5 * d20 / (r**4) * (3.0 * np.sin(fi_e) ** 2 - 1.0)
    gfie = -1.5 * d20 / (r**4) * np.sin(2.0 * fi_e)

    # --- Проекции на оси локального горизонта: вдоль меридиана и «вверх» ---
    gn = gr * cos_mu + gfie * sin_mu
    gfi = -gr * sin_mu + gfie * cos_mu

    # Истинная гравитация в географической СК (третья компонента по модели = 0)
    gg = np.array([gfi, gn, 0.0], dtype=float)

    # Кажущаяся тяжесть: нормальная ось минус центробежное от вращения Земли
    gtn = gn - r * Ue**2 * np.cos(fi_e) * np.cos(FI)
    gtg = np.array([0.0, gtn, 0.0], dtype=float)

    return gg, R1, R2, gtg
