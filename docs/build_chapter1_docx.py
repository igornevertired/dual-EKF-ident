def set_run_font(run, name: str = "Times New Roman", size: int = 14, bold: bool = False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)


def set_paragraph_format(p, first_line: bool = True, align="justify", space_after: float = 6):
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(0)
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.first_line_indent = Cm(1.25 if first_line else 0)
    p.alignment = {
        "justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "left": WD_ALIGN_PARAGRAPH.LEFT,
    }[align]


def latex_to_omath_xml(latex: str) -> str:
    mml = latex2mathml.converter.convert(latex)
    omml = mathml2omml.convert(mml)
    if "xmlns:m=" not in omml:
        omml = omml.replace("<m:oMath>", f'<m:oMath xmlns:m="{M_NS}">', 1)
    return omml


def add_omath_to_paragraph(paragraph, latex: str, display: bool = False) -> None:
    omml = latex_to_omath_xml(latex)
    if display:
        para = parse_xml(
            f'<m:oMathPara xmlns:m="{M_NS}">'
            + re.sub(r'\sxmlns:m="[^"]*"', "", omml)
            + "</m:oMathPara>"
        )
        paragraph._p.append(para)
    else:
        paragraph._p.append(parse_xml(omml))


def add_heading(doc: Document, text: str, level: int = 1) -> None:
    p = doc.add_paragraph()
    set_paragraph_format(p, first_line=False, align="left", space_after=12)
    run = p.add_run(text)
    set_run_font(run, size={1: 16, 2: 15, 3: 14}.get(level, 14), bold=True)


def add_body(doc: Document, text: str) -> None:
    """Формулы: <<eq:latex>> inline; [[eq:latex]] display (целый абзац)."""
    if text.startswith("[[eq:") and text.endswith("]]") and text.count("[[eq:") == 1:
        latex = text[len("[[eq:") : -2]
        p = doc.add_paragraph()
        set_paragraph_format(p, first_line=False, align="center", space_after=10)
        try:
            add_omath_to_paragraph(p, latex, display=True)
        except Exception:
            run = p.add_run(latex)
            set_run_font(run, size=14, bold=True)
        return

    p = doc.add_paragraph()
    set_paragraph_format(p, first_line=True, align="justify")
    pattern = re.compile(r"<<eq:(.+?)>>")
    pos = 0
    for m in pattern.finditer(text):
        if m.start() > pos:
            run = p.add_run(text[pos : m.start()])
            set_run_font(run, size=14)
        try:
            add_omath_to_paragraph(p, m.group(1), display=False)
        except Exception:
            run = p.add_run(m.group(1))
            set_run_font(run, size=14, bold=True)
        pos = m.end()
    if pos < len(text):
        run = p.add_run(text[pos:])
        set_run_font(run, size=14)


def add_table(doc: Document, headers: list[str], rows: list[list[str]]) -> None:
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    for j, h in enumerate(headers):
        cell = table.rows[0].cells[j]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        set_run_font(run, size=12, bold=True)
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = table.rows[i + 1].cells[j]
            cell.text = ""
            run = cell.paragraphs[0].add_run(val)
            set_run_font(run, size=12)
    doc.add_paragraph()


def E(latex: str) -> str:
    """Inline equation marker. Latex must not contain '>>'."""
    assert ">>" not in latex, latex
    return f"<<eq:{latex}>>"


def D(latex: str) -> str:
    """Display equation marker."""
    return f"[[eq:{latex}]]"


